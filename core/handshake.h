#ifndef WA_HANDSHAKE_H
#define WA_HANDSHAKE_H
#include "noise.h"
#include "ws.h"
#include <stddef.h>
#include <stdint.h>
/* Validate the pinned WhatsApp Noise certificate chain, then produce the encrypted
 * client static key for the ClientFinish message. Fail closed on any error.
 * The calling code must discard the Noise state if this function fails. */
int wa_process_server_hello(wa_noise *n, const wa_server_hello *hello,
    const uint8_t local_static_priv[32], const uint8_t local_static_pub[32],
    uint8_t encrypted_static[48]);
/* Returns a static, non-sensitive stage name on failure; validation is identical. */
int wa_process_server_hello_ex(wa_noise *n,const wa_server_hello *hello,
 const uint8_t local_static_priv[32],const uint8_t local_static_pub[32],
 uint8_t encrypted_static[48],const char **failed_stage);
int wa_make_client_finish(const uint8_t encrypted_static[48], const uint8_t *encrypted_payload,
    size_t encrypted_payload_len, uint8_t *out, size_t capacity, size_t *written);
/* Complete the final cryptographic handshake step for an already authenticated
 * ServerHello. payload is serialized ClientPayload protobuf supplied by caller.
 * On failure, discard state; successful return switches into transport mode.
 * No WhatsApp account credentials are generated by this helper. */
int wa_finish_noise(wa_noise *n, const uint8_t encrypted_static[48],
    const uint8_t *client_payload, size_t client_payload_len,
    uint8_t *out, size_t capacity, size_t *written);
#endif
